#!/usr/bin/env python3
"""Write site/glyphs.js, the glyph set shown on the website, from a font's character map.

Run it after every release that adds or removes characters:

    python3 scripts/site-glyphs.py site/fonts/SundaySerif-VF.woff2 site/glyphs.js

Needs fontTools (and brotli for woff2): pip install fonttools brotli
"""

import json
import sys
import unicodedata

from fontTools.ttLib import TTFont

# Characters that draw nothing on their own: the grid leaves them out.
SKIP = {0x20, 0xA0, 0xAD}


def group(cp: int) -> str:
    ch = chr(cp)
    cat = unicodedata.category(ch)
    decomposed = unicodedata.normalize("NFD", ch)
    if cat.startswith("M"):
        return "Marks"
    if cat == "Nd" or cp in (0xB2, 0xB3, 0xB9, 0xBC, 0xBD, 0xBE):
        return "Figures"
    if cat in ("Lu", "Ll", "Lt", "Lo", "Lm"):
        if cp < 0x80 and ch.isalpha():
            return "Uppercase" if cat == "Lu" else "Lowercase"
        if len(decomposed) > 1 or cp > 0x7F:
            return "Accented & extended"
    if cat == "Sc":
        return "Currency"
    return "Punctuation & symbols"


def main(font_path: str, out_path: str) -> None:
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    order = ["Uppercase", "Lowercase", "Accented & extended", "Figures", "Currency", "Punctuation & symbols", "Marks"]
    groups: dict[str, list] = {name: [] for name in order}
    for cp in sorted(cmap):
        if cp in SKIP:
            continue
        name = unicodedata.name(chr(cp), cmap[cp])
        groups[group(cp)].append([cp, name.title()])
    data = [{"name": name, "glyphs": glyphs} for name, glyphs in groups.items() if glyphs]
    total = sum(len(g["glyphs"]) for g in data)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/site-glyphs.py from the font's character map. Do not edit.\n")
        f.write(f"window.SUNDAY_GLYPHS = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n")
    print(f"{out_path}: {total} characters in {len(data)} groups")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
